//! Directory backend for development and tests. Same contract as Telegram.

use super::ChunkBackend;
use anyhow::{bail, Context, Result};
use async_trait::async_trait;
use bytes::Bytes;
use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};

pub struct LocalBackend {
    dir: PathBuf,
    puts: AtomicU64,
    gets: AtomicU64,
}

impl LocalBackend {
    pub fn new(dir: PathBuf) -> Result<Self> {
        std::fs::create_dir_all(&dir).with_context(|| format!("create {}", dir.display()))?;
        Ok(Self { dir, puts: AtomicU64::new(0), gets: AtomicU64::new(0) })
    }

    /// Locators are generated by us, but the DB is still input: refuse anything
    /// that is not a plain generated file name.
    fn path(&self, locator: &str) -> Result<PathBuf> {
        let ok = !locator.is_empty()
            && locator.len() <= 128
            && locator.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_' || b == b'.')
            && !locator.starts_with('.');
        if !ok {
            bail!("invalid local locator");
        }
        Ok(self.dir.join(locator))
    }
}

#[async_trait]
impl ChunkBackend for LocalBackend {
    fn kind(&self) -> &'static str {
        "local"
    }

    async fn put(&self, name: &str, data: Bytes) -> Result<String> {
        let path = self.path(name)?;
        let tmp = self.path(&format!("{name}.tmp"))?;
        tokio::fs::write(&tmp, &data).await?;
        tokio::fs::rename(&tmp, &path).await?;
        self.puts.fetch_add(1, Ordering::Relaxed);
        Ok(name.to_string())
    }

    async fn get(&self, locator: &str) -> Result<Bytes> {
        self.gets.fetch_add(1, Ordering::Relaxed);
        Ok(Bytes::from(tokio::fs::read(self.path(locator)?).await?))
    }

    async fn delete(&self, locator: &str) -> Result<()> {
        match tokio::fs::remove_file(self.path(locator)?).await {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(e.into()),
        }
    }

    async fn mark_backup(&self, locator: &str) -> Result<()> {
        tokio::fs::write(self.dir.join("LATEST_BACKUP"), locator).await?;
        Ok(())
    }

    async fn latest_backup(&self) -> Result<Option<String>> {
        match tokio::fs::read_to_string(self.dir.join("LATEST_BACKUP")).await {
            Ok(s) => Ok(Some(s.trim().to_string())),
            Err(_) => Ok(None),
        }
    }

    async fn health(&self) -> serde_json::Value {
        serde_json::json!({
            "kind": "local",
            "ok": self.dir.is_dir(),
            "puts": self.puts.load(Ordering::Relaxed),
            "gets": self.gets.load(Ordering::Relaxed),
        })
    }
}
